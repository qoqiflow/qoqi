// Go writes, for a Go application, the types of the steps of the queues
// and, for each queue, an interface its application implements and the
// handler that serves it, with package flow of this module.
func Go(s *flowd.Schema, pkg string, o Options) ([]byte, error) {
	names, by, err := queues(s, o.Queue)
	if err != nil {
		return nil, err
	}
	if pkg == "" {
		pkg = "flows"
	}
	g := &golang{s: s, decoders: map[string]bool{}}
	var all []*flowd.StepInfo
	for _, name := range names {
		all = append(all, by[name]...)
	}

	for _, t := range types(s, all) {
		g.declare(t)
	}
	for _, name := range names {
		g.queue(name, by[name], o.Shapes)
	}
	for len(g.pending) > 0 {
		t := g.pending[0]
		g.pending = g.pending[1:]
		g.decoder(t)
	}
	// What the code uses, imported
	body := g.out.String()
	var head strings.Builder
	fmt.Fprintf(&head, "// Code generated by qoqi gen from %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n", o.Source, pkg)
	for _, imp := range []string{"context", "encoding/json", "fmt"} {
		if strings.Contains(body, imp[strings.LastIndex(imp, "/")+1:]+".") {
			fmt.Fprintf(&head, "\t%q\n", imp)
		}
	}
	head.WriteString("\n\t\"github.com/qoqiflow/qoqi/pkg/flow\"\n)\n")
	out, err := format.Source([]byte(head.String() + body))
	if err != nil {
		return nil, fmt.Errorf("the Go written does not parse: %v\n%s", err, head.String()+body)
	}
	return out, nil
}

type golang struct {
	s        *flowd.Schema
	out      strings.Builder
	decoders map[string]bool // the decoders asked for, by type
	pending  []*flowd.Type
}

func (g *golang) p(format string, args ...any) {
	fmt.Fprintf(&g.out, format+"\n", args...)
}

// comment writes a doc comment, each of its lines.
func (g *golang) comment(text string) {
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		g.p("// %s", strings.TrimSpace(line))
	}
}

// goType is a type as Go writes it.
func (g *golang) goType(t *flowd.Type) string {
	switch t.Kind {
	case "int":
		return "int"
	case "float":
		return "float64"
	case "bool":
		return "bool"
	case "string":
		return "string"
	case "void":
		return "flow.Void"
	case "option":
		if t.Elem.Kind == "enum" && !isResult(t.Elem) {
			// An interface holds nil already
			return g.goType(t.Elem)
		}
		return "*" + g.goType(t.Elem)
	case "array":
		return "[]" + g.goType(t.Elem)
	case "dict":
		return "map[string]" + g.goType(t.Elem)
	case "struct", "enum":
		if isResult(t) {
			return "flow.Result[" + g.goType(t.Args[0]) + ", " + g.goType(t.Args[1]) + "]"
		}
		if isSettled(t) {
			return g.goType(t.Args[0])
		}
		return className(t)
	}
	return "json.RawMessage"
}

// exported is a name of Qoqi as Go exports it: id as ID, authorId as
// AuthorID, card_number as CardNumber.
func exported(name string) string {
	initialisms := map[string]string{"id": "ID", "url": "URL", "uri": "URI", "api": "API", "http": "HTTP", "json": "JSON", "ip": "IP", "uuid": "UUID", "sku": "SKU", "iban": "IBAN"}
	var words []string
	word := ""
	for i, r := range name {
		switch {
		case r == '_' || r == '-':
			words, word = append(words, word), ""
		case r >= 'A' && r <= 'Z' && i > 0:
			words, word = append(words, word), string(r)
		default:
			word += string(r)
		}
	}
	words = append(words, word)
	var out strings.Builder
	for _, w := range words {
		if w == "" {
			continue
		}
		if i, ok := initialisms[strings.ToLower(w)]; ok {
			out.WriteString(i)
			continue
		}
		out.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return out.String()
}

// local is a name of Qoqi as a Go variable, out of the way of Go's
// words and of the names the code written uses.
func local(name string) string {
	switch name {
	case "break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough", "for", "func", "go", "goto",
		"if", "import", "interface", "map", "package", "range", "return", "select", "struct", "switch", "type", "var",
		"ctx", "task", "args", "err", "result", "undo", "steps", "q", "flow", "json", "fmt", "context":
		return name + "_"
	}
	return name
}

func (g *golang) declare(t *flowd.Type) {
	d := g.s.Types[t.Name]
	name := className(t)
	g.p("")
	if d.Doc != "" {
		doc := strings.TrimSpace(d.Doc)
		g.comment(name + ": " + strings.ToLower(doc[:1]) + doc[1:])
	}
	if d.Kind == "struct" {
		g.p("type %s struct {", name)
		for _, f := range d.Fields {
			g.p("\t%s %s `json:\"%s\"`", exported(f.Name), g.goType(f.Type), f.Name)
		}
		g.p("}")
		return
	}

	var variants []string
	for _, v := range d.Variants {
		variants = append(variants, v.Name)
	}
	if d.Doc == "" {
		g.p("// %s is one of %s.", name, strings.Join(variants, ", "))
	}
	g.p("type %s interface {", name)
	g.p("\tis%s()", name)
	g.p("}")
	for _, v := range d.Variants {
		vn := name + v.Name
		g.p("")
		switch {
		case len(v.Values) == 0:
			g.p("type %s struct{}", vn)
		case v.Named:
			g.p("type %s struct {", vn)
			for _, f := range v.Values {
				g.p("\t%s %s", exported(f.Name), g.goType(f.Type))
			}
			g.p("}")
		case len(v.Values) == 1:
			g.p("type %s struct {", vn)
			g.p("\tValue %s", g.goType(v.Values[0].Type))
			g.p("}")
		default:
			g.p("type %s struct {", vn)
			for i, f := range v.Values {
				g.p("\tValue%d %s", i, g.goType(f.Type))
			}
			g.p("}")
		}
		g.p("")
		g.p("func (%s) is%s() {}", vn, name)
		g.p("")
		g.p("func (v %s) MarshalJSON() ([]byte, error) {", vn)
		switch {
		case len(v.Values) == 0:
			g.p("\treturn json.Marshal(%q)", v.Name)
		case v.Named:
			var pairs []string
			for _, f := range v.Values {
				pairs = append(pairs, fmt.Sprintf("%q: v.%s", f.Name, exported(f.Name)))
			}
			g.p("\treturn json.Marshal(map[string]any{%q: map[string]any{%s}})", v.Name, strings.Join(pairs, ", "))
		case len(v.Values) == 1:
			g.p("\treturn json.Marshal(map[string]any{%q: v.Value})", v.Name)
		default:
			var values []string
			for i := range v.Values {
				values = append(values, fmt.Sprintf("v.Value%d", i))
			}
			g.p("\treturn json.Marshal(map[string]any{%q: []any{%s}})", v.Name, strings.Join(values, ", "))
		}
		g.p("}")
	}
}

// needs says whether a type is read with a decoder of its own: json
// cannot read an interface, so whatever holds an enum needs one.
func (g *golang) needs(t *flowd.Type, seen map[string]bool) bool {
	switch t.Kind {
	case "option", "array", "dict":
		return g.needs(t.Elem, seen)
	case "struct", "enum":
		if isResult(t) {
			return true
		}
		if t.Kind == "enum" {
			return true
		}
		if seen[t.Name] {
			return false
		}
		seen[t.Name] = true
		if d := g.s.Types[t.Name]; d != nil {
			for _, f := range d.Fields {
				if g.needs(f.Type, seen) {
					return true
				}
			}
		}
	}
	return false
}

// decode is the decoder of a type, as an expression of Go.
func (g *golang) decode(t *flowd.Type) string {
	if !g.needs(t, map[string]bool{}) {
		return "flow.Decode[" + g.goType(t) + "]"
	}
	switch t.Kind {
	case "option":
		if t.Elem.Kind == "enum" && !isResult(t.Elem) {
			return g.decode(t.Elem)
		}
		return "flow.DecodeOption(" + g.decode(t.Elem) + ")"
	case "array":
		return "flow.DecodeList(" + g.decode(t.Elem) + ")"
	case "dict":
		return "flow.DecodeMap(" + g.decode(t.Elem) + ")"
	}
	if isResult(t) {
		return "flow.DecodeResult(" + g.decode(t.Args[0]) + ", " + g.decode(t.Args[1]) + ")"
	}
	if !g.decoders[t.Name] {
		g.decoders[t.Name] = true
		g.pending = append(g.pending, t)
	}
	return "decode" + className(t)
}

// decoder writes the decoder of a struct or an enum json cannot read.
func (g *golang) decoder(t *flowd.Type) {
	d := g.s.Types[t.Name]
	name := className(t)
	g.p("")
	g.p("func decode%s(data json.RawMessage) (%s, error) {", name, name)
	if d.Kind == "struct" {
		g.p("\tvar fields map[string]json.RawMessage")
		g.p("\tif err := json.Unmarshal(data, &fields); err != nil {")
		g.p("\t\treturn %s{}, fmt.Errorf(\"a %s is an object: %%w\", err)", name, name)
		g.p("\t}")
		g.p("\tvar v %s", name)
		g.p("\tvar err error")
		for _, f := range d.Fields {
			g.p("\tif v.%s, err = flow.Field(fields, %q, %s); err != nil {", exported(f.Name), f.Name, g.decode(f.Type))
			g.p("\t\treturn v, err")
			g.p("\t}")
		}
		g.p("\treturn v, nil")
		g.p("}")
		return
	}
	g.p("\tif string(data) == \"null\" {")
	g.p("\t\treturn nil, nil")
	g.p("\t}")
	g.p("\tvariant, values, err := flow.Variant(data)")
	g.p("\tif err != nil {")
	g.p("\t\treturn nil, err")
	g.p("\t}")
	g.p("\tswitch variant {")
	var names []string
	for _, v := range d.Variants {
		names = append(names, v.Name)
		vn := name + v.Name
		g.p("\tcase %q:", v.Name)
		switch {
		case len(v.Values) == 0:
			g.p("\t\treturn %s{}, nil", vn)
		case len(v.Values) == 1 && !v.Named:
			g.p("\t\tvalue, err := %s(values)", g.decode(v.Values[0].Type))
			g.p("\t\treturn %s{Value: value}, err", vn)
		case v.Named:
			g.p("\t\tvar fields map[string]json.RawMessage")
			g.p("\t\tif err := json.Unmarshal(values, &fields); err != nil {")
			g.p("\t\t\treturn nil, fmt.Errorf(\"%s holds an object: %%w\", err)", v.Name)
			g.p("\t\t}")
			g.p("\t\tvar v %s", vn)
			for _, f := range v.Values {
				g.p("\t\tif v.%s, err = flow.Field(fields, %q, %s); err != nil {", exported(f.Name), f.Name, g.decode(f.Type))
				g.p("\t\t\treturn nil, err")
				g.p("\t\t}")
			}
			g.p("\t\treturn v, nil")
		default:
			g.p("\t\tvar items []json.RawMessage")
			g.p("\t\tif err := json.Unmarshal(values, &items); err != nil || len(items) != %d {", len(v.Values))
			g.p("\t\t\treturn nil, fmt.Errorf(\"%s holds %d values\")", v.Name, len(v.Values))
			g.p("\t\t}")
			g.p("\t\tvar v %s", vn)
			for i, f := range v.Values {
				g.p("\t\tif v.Value%d, err = %s(items[%d]); err != nil {", i, g.decode(f.Type), i)
				g.p("\t\t\treturn nil, err")
				g.p("\t\t}")
			}
			g.p("\t\treturn v, nil")
		}
	}
	g.p("\t}")
	g.p("\treturn nil, fmt.Errorf(\"a %s is one of %s, not %%q\", variant)", name, strings.Join(names, ", "))
	g.p("}")
}

// signature is a step as Qoqi declares it, for its comment.
func signature(step *flowd.StepInfo) string {
	var params []string
	for _, p := range step.Params {
		params = append(params, p.Name+": "+p.Type.Text)
	}
	text := "step fn " + stepName(step) + "(" + strings.Join(params, ", ") + ")"
	if step.Returns.Kind != "void" {
		text += " -> " + step.Returns.Text
	}
	text += " by " + step.Queue
	if step.Undo != "" {
		text += " undo " + step.Undo
	}
	return text
}

func (g *golang) queue(queue string, steps []*flowd.StepInfo, shapes map[string]string) {
	iface := pascal(queue)
	g.p("")
	g.p("// %s carries out the steps of the queue %s. A step answers what it", iface, queue)
	g.p("// returns; an error is a failure of its body, but for flow.Retry,")
	g.p("// flow.ErrLater and flow.ErrUnknown.")
	g.p("type %s interface {", iface)
	for i, step := range steps {
		if i > 0 {
			g.p("")
		}
		g.p("\t// %s", signature(step))
		if step.Doc != "" {
			g.p("\t//")
			for _, line := range strings.Split(strings.TrimSpace(step.Doc), "\n") {
				g.p("\t// %s", strings.TrimSpace(line))
			}
		}
		if isSettled(step.Returns) {
			g.p("\t//")
			g.p("\t// It returns what is Done: the daemon gives Unknown when nothing says")
			g.p("\t// what came of it.")
		}
		if u := undoParam(g.s, step); u != nil {
			g.p("\t//")
			g.p("\t// It gives what %s is given with every value that is not an Err.", step.Undo)
		}
		g.p("\t%s", g.method(step))
	}
	g.p("}")

	g.p("")
	g.p("// The shapes of the steps of %s: which handler answers which step.", queue)
	g.p("const (")
	for _, step := range steps {
		g.p("\t%sShape = %q", exported(stepName(step)), shapes[stepName(step)])
	}
	g.p(")")

	g.p("")
	g.p("// %sQueue serves the queue %s, its steps carried out by steps: the", iface, queue)
	g.p("// handler of the address qoqi.json gives it.")
	g.p("func %sQueue(steps %s, secrets ...string) *flow.Queue {", iface, iface)
	g.p("\tq := flow.NewQueue(%q, secrets...)", queue)
	for _, step := range steps {
		g.handler(step)
	}
	g.p("\treturn q")
	g.p("}")
}

// method is a step's method in the interface.
func (g *golang) method(step *flowd.StepInfo) string {
	params := []string{"ctx context.Context", "task *flow.Task"}
	for _, p := range step.Params {
		params = append(params, local(p.Name)+" "+g.goType(p.Type))
	}
	returns := "error"
	if step.Returns.Kind != "void" {
		returns = "(" + g.goType(done(step.Returns))
		if u := undoParam(g.s, step); u != nil {
			returns += ", *" + g.goType(u)
		}
		returns += ", error)"
	}
	return exported(stepName(step)) + "(" + strings.Join(params, ", ") + ") " + returns
}

func (g *golang) handler(step *flowd.StepInfo) {
	name := exported(stepName(step))
	g.p("\tq.Handle(%sShape, func(ctx context.Context, task *flow.Task) flow.Answer {", name)
	var call []string
	call = append(call, "ctx", "task")
	if len(step.Params) > 0 {
		g.p("\t\tvar args map[string]json.RawMessage")
		g.p("\t\tif err := json.Unmarshal(task.Args, &args); err != nil {")
		g.p("\t\t\treturn flow.Failure(err)")
		g.p("\t\t}")
		for _, p := range step.Params {
			g.p("\t\t%s, err := flow.Field(args, %q, %s)", local(p.Name), p.Name, g.decode(p.Type))
			g.p("\t\tif err != nil {")
			g.p("\t\t\treturn flow.Failure(err)")
			g.p("\t\t}")
			call = append(call, local(p.Name))
		}
	}
	invoke := "steps." + name + "(" + strings.Join(call, ", ") + ")"
	switch {
	case step.Returns.Kind == "void":
		g.p("\t\tif err := %s; err != nil {", invoke)
		g.p("\t\t\treturn flow.AnswerOf(err)")
		g.p("\t\t}")
		g.p("\t\treturn flow.Answered(flow.Value(nil))")
	case undoParam(g.s, step) != nil:
		g.p("\t\tresult, undo, err := %s", invoke)
		g.p("\t\tif err != nil {")
		g.p("\t\t\treturn flow.AnswerOf(err)")
		g.p("\t\t}")
		g.p("\t\tif undo != nil {")
		g.p("\t\t\treturn flow.Answered(flow.WithUndo(result, undo))")
		g.p("\t\t}")
		g.p("\t\treturn flow.Answered(flow.Value(result))")
	default:
		g.p("\t\tresult, err := %s", invoke)
		g.p("\t\tif err != nil {")
		g.p("\t\t\treturn flow.AnswerOf(err)")
		g.p("\t\t}")
		if isSettled(step.Returns) {
			g.p("\t\treturn flow.Answered(flow.Value(flow.Done(result)))")
		} else {
			g.p("\t\treturn flow.Answered(flow.Value(result))")
		}
	}
	g.p("\t})")
}
