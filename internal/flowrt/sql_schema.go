func schemaOf(kind sqldb.Kind) []string {
	text := sqliteSchema
	switch kind {
	case sqldb.Postgres:
		text = postgresSchema
	case sqldb.MySQL:
		text = mysqlSchema
	}
	var out []string
	for _, statement := range strings.Split(text, ";") {
		if strings.TrimSpace(statement) != "" {
			out = append(out, statement)
		}
	}
	return out
}

// tables are the names of the tables, and of the indexes, of a program's
// store: the ones a prefix goes before.
var tables = regexp.MustCompile(`\b(instances_due|instances|steps|versions|messages_waiting|messages|attempts_under_way|attempts)\b`)

var (
	// Words MySQL keeps for itself that are columns here: quoted there
	mysqlReserved = regexp.MustCompile(`\b(row|key|until|lock|undo)\b`)
	// An insert that leaves a row there as it is: the first column of
	// the key is set to itself, which changes nothing and counts no row
	doNothing = regexp.MustCompile(`ON CONFLICT\s*\(\s*(\w+)[^)]*\)\s*DO NOTHING`)
	doUpdate  = regexp.MustCompile(`ON CONFLICT\s*\([^)]*\)\s*DO UPDATE SET`)
	excluded  = regexp.MustCompile(`\bexcluded\.(\w+)`)
)

// dialect writes a query, written as SQLite takes it, as the kind of
// database does: an upsert as MySQL writes it, instr as Postgres does,
// and the parameters of Postgres numbered.
func dialect(kind sqldb.Kind, query string) string {
	switch kind {
	case sqldb.Postgres:
		query = strings.ReplaceAll(query, "instr(", "strpos(")
		query = strings.ReplaceAll(query, "x''", "''::bytea")
	case sqldb.MySQL:
		query = doNothing.ReplaceAllString(query, "ON DUPLICATE KEY UPDATE $1 = $1")
		query = doUpdate.ReplaceAllString(query, "ON DUPLICATE KEY UPDATE")
		query = excluded.ReplaceAllString(query, "VALUES($1)")
		query = mysqlReserved.ReplaceAllString(query, "`$1`")
	}
	return kind.Rebind(query)
}
