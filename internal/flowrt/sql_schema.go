// The tables of a store, as each kind of database writes them. The
// queries name them as SQLite does; dialect rewrites what differs.
//
// On Postgres, names and keys compare as their bytes (COLLATE "C"), as
// SQLite's do: a step's results are found by the keys between a prefix
// and the greatest text that starts with it. On MySQL, every text does
// (utf8mb4_bin), and what is looked up by is a VARCHAR, since a TEXT
// cannot be a key there: a name of an instance is at most 255
// characters, a key of a step 760.

const sqliteSchema = `
CREATE TABLE IF NOT EXISTS instances (
    id      TEXT PRIMARY KEY,
    flow    TEXT NOT NULL,
    status  TEXT NOT NULL,
    wake_at INTEGER NOT NULL,
    row     TEXT NOT NULL,
    cancel  TEXT NOT NULL DEFAULT '',
    awaits  TEXT NOT NULL DEFAULT '',
    held_by    TEXT NOT NULL DEFAULT '',
    held_until INTEGER NOT NULL DEFAULT 0,
    held_as    TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS instances_due ON instances(status, wake_at);
CREATE TABLE IF NOT EXISTS versions (
    fingerprint TEXT PRIMARY KEY,
    bytecode    BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS messages (
    seq      INTEGER PRIMARY KEY AUTOINCREMENT,
    instance TEXT NOT NULL,
    inbox    TEXT NOT NULL,
    key      TEXT NOT NULL,
    data     TEXT NOT NULL,
    taken    INTEGER NOT NULL DEFAULT 0,
    pass     INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS messages_waiting ON messages(instance, inbox, taken);
CREATE TABLE IF NOT EXISTS steps (
    key    TEXT PRIMARY KEY,
    result TEXT NOT NULL,
    undo   TEXT NOT NULL DEFAULT '',
    asked  TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS attempts (
    key      TEXT NOT NULL,
    attempt  INTEGER NOT NULL,
    instance TEXT NOT NULL,
    step     TEXT NOT NULL,
    token    TEXT NOT NULL,
    until    INTEGER NOT NULL,
    state    TEXT NOT NULL,
    settled  INTEGER NOT NULL DEFAULT 0,
    undo     TEXT NOT NULL DEFAULT '',
    answer   TEXT NOT NULL DEFAULT '',
    late     TEXT NOT NULL DEFAULT '',
    queue    TEXT NOT NULL DEFAULT '',
    said     TEXT NOT NULL DEFAULT '',
    shape    TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (key, attempt)
);
CREATE TABLE IF NOT EXISTS deploys (
    seq      INTEGER PRIMARY KEY AUTOINCREMENT,
    name     TEXT NOT NULL,
    version  TEXT NOT NULL,
    at       INTEGER NOT NULL,
    package  BLOB NOT NULL,
    lock     TEXT NOT NULL,
    report   TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS deploys_by_name ON deploys(name, seq);
`

